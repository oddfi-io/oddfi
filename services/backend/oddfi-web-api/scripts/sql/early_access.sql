CREATE TABLE `early_access_registrations` (
  `id`                     BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `biz_id`                 VARCHAR(32)  NOT NULL COMMENT '业务 ID，ea_xxxxxxxxxxxx',
  `email`                  VARCHAR(128) NOT NULL COMMENT '邮箱（小写归一化）',
  `wallet_address`         VARCHAR(64)  NOT NULL COMMENT 'BSC 钱包（小写归一化）',
  `expected_feature`       TEXT         DEFAULT NULL,
  `referral_source`        VARCHAR(32)  DEFAULT NULL,
  `referral_source_other`  VARCHAR(64)  DEFAULT NULL,
  `source`                 VARCHAR(32)  DEFAULT NULL,
  `utm_source`             VARCHAR(64)  DEFAULT NULL,
  `utm_campaign`           VARCHAR(64)  DEFAULT NULL,
  `ip_address`             VARCHAR(64)  DEFAULT NULL,
  `user_agent`             TEXT         DEFAULT NULL,
  `status`                 TINYINT      NOT NULL DEFAULT 1,
  `created_at`             TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at`             TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_biz_id` (`biz_id`),
  UNIQUE KEY `uk_email` (`email`),
  UNIQUE KEY `uk_wallet` (`wallet_address`),
  KEY `idx_created_at` (`created_at`),
  KEY `idx_referral_source` (`referral_source`),
  KEY `idx_source` (`source`),
  KEY `idx_utm_source` (`utm_source`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='早鸟登记表';
