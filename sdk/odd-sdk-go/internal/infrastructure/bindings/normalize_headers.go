//go:build ignore

package main

import (
	"bytes"
	"fmt"
	"os"
)

var (
	oldHeader = []byte("// Code generated - DO NOT EDIT.\n")
	newHeader = []byte("// Code generated by abigen. DO NOT EDIT.\n")
)

func main() {
	for _, path := range os.Args[1:] {
		if path == "--" {
			continue
		}
		if err := normalize(path); err != nil {
			fmt.Fprintf(os.Stderr, "%s: %v\n", path, err)
			os.Exit(1)
		}
	}
}

func normalize(path string) error {
	content, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	if bytes.HasPrefix(content, newHeader) {
		return nil
	}
	if !bytes.HasPrefix(content, oldHeader) {
		return fmt.Errorf("unexpected generated header")
	}
	updated := append(append([]byte{}, newHeader...), content[len(oldHeader):]...)
	return os.WriteFile(path, updated, 0o644)
}
